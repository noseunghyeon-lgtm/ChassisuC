function crc = CalcCRCJ1939(msg_id, msg_data, source_address)
% CalcCRCJ1939 - J1939 CAN 메시지의 CRC를 계산하는 함수
%
%   출처: 사용자 제공·검증 완료 (Issue #6, C23). CRC-8 H2F 룩업 테이블 기반.
%   Chassis uC E2E 보호용 CRC. CRC8-SAEJ1850 계열(H2F) 규칙을 따른다.
%
% CRC 계산 순서:
% Data Byte 2 + Data Byte 3 + Data Byte 4 + Data Byte 5 + Data Byte 6 +
% Data Byte 7 + Data Byte 8 + Source Address + PGN LSB + PGN 2nd byte + PGN MSB
%
% 입력:
%   msg_id         - CAN 메시지 ID (29-bit extended ID)
%                    hex2dec('18FEF100') 또는 402641152 형식
%   msg_data       - 메시지 데이터 바이트 배열 (1 x 8), Data Byte 1은 CRC
%                    [0x00, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88] 형식
%   source_address - 소스 어드레스 (8-bit)
%                    hex2dec('00') 또는 0 형식
%
% 출력:
%   crc            - 계산된 CRC 값 (8-bit), Data Byte 1에 위치
%
% 예제 1: hex 값으로 입력
%   msg_id = hex2dec('18FEF100');
%   msg_data = [0x00, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88];
%   source_addr = hex2dec('00');
%   crc = CalcCRCJ1939(msg_id, msg_data, source_addr);
%
% 예제 2: 10진수 값으로 입력
%   msg_id = 402641152;
%   msg_data = [0, 34, 51, 68, 85, 102, 119, 136];
%   source_addr = 0;
%   crc = CalcCRCJ1939(msg_id, msg_data, source_addr);
%
% 예제 3: 개별 바이트로 입력
%   msg_id = hex2dec('18FEF100');
%   byte2 = 0x22; byte3 = 0x33; byte4 = 0x44; byte5 = 0x55;
%   byte6 = 0x66; byte7 = 0x77; byte8 = 0x88;
%   msg_data = [0x00, byte2, byte3, byte4, byte5, byte6, byte7, byte8];
%   source_addr = 0x00;
%   crc = CalcCRCJ1939(msg_id, msg_data, source_addr);

    % CRC-8 H2F 룩업 테이블
    CRC_8H2F_Tbl = uint8([...
        0x00, 0x2F, 0x5E, 0x71, 0xBC, 0x93, 0xE2, 0xCD, ...
        0x57, 0x78, 0x09, 0x26, 0xEB, 0xC4, 0xB5, 0x9A, ...
        0xAE, 0x81, 0xF0, 0xDF, 0x12, 0x3D, 0x4C, 0x63, ...
        0xF9, 0xD6, 0xA7, 0x88, 0x45, 0x6A, 0x1B, 0x34, ...
        0x73, 0x5C, 0x2D, 0x02, 0xCF, 0xE0, 0x91, 0xBE, ...
        0x24, 0x0B, 0x7A, 0x55, 0x98, 0xB7, 0xC6, 0xE9, ...
        0xDD, 0xF2, 0x83, 0xAC, 0x61, 0x4E, 0x3F, 0x10, ...
        0x8A, 0xA5, 0xD4, 0xFB, 0x36, 0x19, 0x68, 0x47, ...
        0xE6, 0xC9, 0xB8, 0x97, 0x5A, 0x75, 0x04, 0x2B, ...
        0xB1, 0x9E, 0xEF, 0xC0, 0x0D, 0x22, 0x53, 0x7C, ...
        0x48, 0x67, 0x16, 0x39, 0xF4, 0xDB, 0xAA, 0x85, ...
        0x1F, 0x30, 0x41, 0x6E, 0xA3, 0x8C, 0xFD, 0xD2, ...
        0x95, 0xBA, 0xCB, 0xE4, 0x29, 0x06, 0x77, 0x58, ...
        0xC2, 0xED, 0x9C, 0xB3, 0x7E, 0x51, 0x20, 0x0F, ...
        0x3B, 0x14, 0x65, 0x4A, 0x87, 0xA8, 0xD9, 0xF6, ...
        0x6C, 0x43, 0x32, 0x1D, 0xD0, 0xFF, 0x8E, 0xA1, ...
        0xE3, 0xCC, 0xBD, 0x92, 0x5F, 0x70, 0x01, 0x2E, ...
        0xB4, 0x9B, 0xEA, 0xC5, 0x08, 0x27, 0x56, 0x79, ...
        0x4D, 0x62, 0x13, 0x3C, 0xF1, 0xDE, 0xAF, 0x80, ...
        0x1A, 0x35, 0x44, 0x6B, 0xA6, 0x89, 0xF8, 0xD7, ...
        0x90, 0xBF, 0xCE, 0xE1, 0x2C, 0x03, 0x72, 0x5D, ...
        0xC7, 0xE8, 0x99, 0xB6, 0x7B, 0x54, 0x25, 0x0A, ...
        0x3E, 0x11, 0x60, 0x4F, 0x82, 0xAD, 0xDC, 0xF3, ...
        0x69, 0x46, 0x37, 0x18, 0xD5, 0xFA, 0x8B, 0xA4, ...
        0x05, 0x2A, 0x5B, 0x74, 0xB9, 0x96, 0xE7, 0xC8, ...
        0x52, 0x7D, 0x0C, 0x23, 0xEE, 0xC1, 0xB0, 0x9F, ...
        0xAB, 0x84, 0xF5, 0xDA, 0x17, 0x38, 0x49, 0x66, ...
        0xFC, 0xD3, 0xA2, 0x8D, 0x40, 0x6F, 0x1E, 0x31, ...
        0x76, 0x59, 0x28, 0x07, 0xCA, 0xE5, 0x94, 0xBB, ...
        0x21, 0x0E, 0x7F, 0x50, 0x9D, 0xB2, 0xC3, 0xEC, ...
        0xD8, 0xF7, 0x86, 0xA9, 0x64, 0x4B, 0x3A, 0x15, ...
        0x8F, 0xA0, 0xD1, 0xFE, 0x33, 0x1C, 0x6D, 0x42 ...
    ]);

    % 데이터를 uint8로 변환
    msg_data = uint8(msg_data);
    source_address = uint8(source_address);

    % CRC 초기값
    crc = uint8(255);

    % 1. Data Byte 2~8에 대한 CRC 계산 (Data Byte 1은 CRC이므로 제외)
    for i = 2:8
        if i <= length(msg_data)
            idx = uint16(bitxor(crc, msg_data(i))) + uint16(1);
            crc = CRC_8H2F_Tbl(idx);
        end
    end

    % 2. Source Address에 대한 CRC 계산
    idx = uint16(bitxor(crc, source_address)) + uint16(1);
    crc = CRC_8H2F_Tbl(idx);

    % 3. PGN 추출 (from 29-bit CAN ID)
    % J1939 CAN ID 구조: [Priority(3bit)][Reserved(1bit)][DP(1bit)][PF(8bit)][PS(8bit)][SA(8bit)]
    % PGN = [DP][PF][PS] (PS는 PF >= 240일 때만 포함)

    msg_id_u32 = uint32(msg_id);
    PF = uint8(bitand(bitshift(msg_id_u32, -16), uint32(255)));  % PGN MSB
    PS = uint8(bitand(bitshift(msg_id_u32, -8), uint32(255)));   % PGN 2nd byte
    DP = uint8(bitand(bitshift(msg_id_u32, -24), uint32(1)));    % Data Page bit

    % PGN LSB, 2nd byte, MSB 결정
    if PF < uint8(240)  % PDU1 format (destination specific)
        PGN_LSB = uint8(0);      % PS는 destination address이므로 PGN에서 0
        PGN_2nd = PF;
    else  % PDU2 format (broadcast)
        PGN_LSB = PS;
        PGN_2nd = PF;
    end
    PGN_MSB = DP;  % Data Page (상위 비트)

    % 4. PGN LSB에 대한 CRC 계산
    idx = uint16(bitxor(crc, PGN_LSB)) + uint16(1);
    crc = CRC_8H2F_Tbl(idx);

    % 5. PGN 2nd byte에 대한 CRC 계산
    idx = uint16(bitxor(crc, PGN_2nd)) + uint16(1);
    crc = CRC_8H2F_Tbl(idx);

    % 6. PGN MSB에 대한 CRC 계산
    idx = uint16(bitxor(crc, PGN_MSB)) + uint16(1);
    crc = CRC_8H2F_Tbl(idx);

    % 7. 최종 XOR
    crc = bitxor(crc, uint8(255));
end
